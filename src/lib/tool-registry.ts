// ─── HELPER FUNCTIONS ───────────────────────────────────────────

export function getCategoryBySlug(slug: string): Category | undefined {
  return categories.find((c) => c.slug === slug);
}

export function getSubcategoryBySlug(categorySlug: string, subcategorySlug: string): Subcategory | undefined {
  return subcategories.find((s) => s.categorySlug === categorySlug && s.slug === subcategorySlug);
}

export function getSubcategoriesByCategory(categorySlug: string): Subcategory[] {
  return subcategories.filter((s) => s.categorySlug === categorySlug);
}

export function getToolsByCategory(categorySlug: string): Tool[] {
  return tools.filter((t) => t.category === categorySlug);
}

export function getToolsBySubcategory(categorySlug: string, subcategorySlug: string): Tool[] {
  return tools.filter((t) => t.category === categorySlug && t.subcategory === subcategorySlug);
}

export function getToolBySlug(categorySlug: string, toolSlug: string, subcategorySlug?: string): Tool | undefined {
  return tools.find(
    (t) => t.category === categorySlug && t.slug === toolSlug && (subcategorySlug ? t.subcategory === subcategorySlug : !t.subcategory)
  );
}

export function getToolByAnySlug(toolSlug: string): Tool | undefined {
  return tools.find((t) => t.slug === toolSlug);
}

export function getRelatedTools(tool: Tool): Tool[] {
  return tool.relatedSlugs
    .map((slug) => tools.find((t) => t.slug === slug))
    .filter((t): t is Tool => t !== undefined);
}

export function getToolUrl(tool: Tool): string {
  if (tool.subcategory) {
    return `/tools/${tool.category}/${tool.subcategory}/${tool.slug}`;
  }
  return `/tools/${tool.category}/${tool.slug}`;
}

export function getCategoryUrl(category: Category): string {
  return `/tools/${category.slug}`;
}

export function getSubcategoryUrl(subcategory: Subcategory): string {
  return `/tools/${subcategory.categorySlug}/${subcategory.slug}`;
}

export function getToolCount(categorySlug: string): number {
  return tools.filter((t) => t.category === categorySlug).length;
}

export function getSubcategoryToolCount(categorySlug: string, subcategorySlug: string): number {
  return tools.filter((t) => t.category === categorySlug && t.subcategory === subcategorySlug).length;
}

